// Command reset generates Reset methods for structures marked // generate:reset.
// Run it from the module root: go run ./cmd/reset.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const generatedHeader = "// Code generated by reset; DO NOT EDIT.\n"

func main() {
	if err := generate("."); err != nil {
		log.Fatal(err)
	}
}

// generate scans the current module's packages, respecting Go build constraints.
// Test files, vendor, testdata and nested modules follow go list ./... semantics.
func generate(root string) error {
	pkgs, err := packages.Load(&packages.Config{
		Dir: root, Mode: packages.LoadSyntax,
	}, "./...")
	if err != nil {
		return fmt.Errorf("load packages: %w", err)
	}
	type output struct {
		path string
		data []byte
	}
	var outputs []output
	for _, pkg := range pkgs {
		if len(pkg.Errors) != 0 {
			return fmt.Errorf("load %s: %v", pkg.PkgPath, pkg.Errors)
		}
		data, err := generatePackage(pkg)
		if err != nil {
			return fmt.Errorf("generate %s: %w", pkg.PkgPath, err)
		}
		if len(pkg.GoFiles) == 0 {
			continue
		}
		path := filepath.Join(filepath.Dir(pkg.GoFiles[0]), "reset.gen.go")
		old, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if err == nil && !bytes.HasPrefix(old, []byte(generatedHeader)) {
			if data != nil {
				return fmt.Errorf("refusing to overwrite %s: not generated by reset", path)
			}
			continue
		}
		if !bytes.Equal(old, data) {
			outputs = append(outputs, output{path, data})
		}
	}
	// Validate every package before modifying any generated files.
	for _, out := range outputs {
		if out.data == nil {
			err = os.Remove(out.path)
		} else {
			err = os.WriteFile(out.path, out.data, 0o644)
		}
		if err != nil {
			return fmt.Errorf("write %s: %w", out.path, err)
		}
	}
	return nil
}

func marked(group *ast.CommentGroup) bool {
	if group == nil {
		return false
	}
	for _, comment := range group.List {
		text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
		if text == "generate:reset" {
			return true
		}
	}
	return false
}

func generatePackage(pkg *packages.Package) ([]byte, error) {
	var targets []*types.Named
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			group, ok := decl.(*ast.GenDecl)
			if !ok || group.Tok != token.TYPE {
				continue
			}
			for _, spec := range group.Specs {
				spec := spec.(*ast.TypeSpec)
				if !marked(spec.Doc) && !marked(group.Doc) {
					continue
				}
				if _, ok := spec.Type.(*ast.StructType); !ok || spec.Assign.IsValid() {
					continue
				}
				named, ok := pkg.TypesInfo.Defs[spec.Name].Type().(*types.Named)
				if !ok {
					return nil, fmt.Errorf("cannot resolve structure %s", spec.Name.Name)
				}
				for i := 0; i < named.NumMethods(); i++ {
					method := named.Method(i)
					if method.Name() == "Reset" && filepath.Base(pkg.Fset.Position(method.Pos()).Filename) != "reset.gen.go" {
						return nil, fmt.Errorf("%s already declares Reset", spec.Name.Name)
					}
				}
				targets = append(targets, named)
			}
		}
	}
	if len(targets) == 0 {
		return nil, nil
	}
	sort.Slice(targets, func(i, j int) bool { return targets[i].Obj().Name() < targets[j].Obj().Name() })
	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "\npackage %s\n", pkg.Name)
	for _, named := range targets {
		name := named.Obj().Name()
		var params []string
		receiver := "rs"
		for i := 0; i < named.TypeParams().Len(); i++ {
			params = append(params, named.TypeParams().At(i).Obj().Name())
		}
		for contains(params, receiver) {
			receiver += "_"
		}
		if len(params) != 0 {
			name += "[" + strings.Join(params, ", ") + "]"
		}
		fmt.Fprintf(&b, "\n// Reset resets the fields of %s, retaining slices, maps and pointers.\n", named.Obj().Name())
		fmt.Fprintf(&b, "func (%s *%s) Reset() {\nif %s == nil { return }\n", receiver, name, receiver)
		structure := named.Underlying().(*types.Struct)
		for i := 0; i < structure.NumFields(); i++ {
			field := structure.Field(i)
			if field.Name() == "_" {
				continue
			}
			if err := resetField(&b, receiver+"."+field.Name(), field.Type(), 0); err != nil {
				return nil, fmt.Errorf("%s.%s: %w", name, field.Name(), err)
			}
		}
		b.WriteString("}\n")
	}
	return format.Source([]byte(b.String()))
}

func contains(names []string, name string) bool {
	for _, candidate := range names {
		if candidate == name {
			return true
		}
	}
	return false
}

// resetField emits type-directed operations without importing field types.
func resetField(b *strings.Builder, expr string, typ types.Type, depth int) error {
	if _, ok := types.Unalias(typ).(*types.TypeParam); ok {
		return fmt.Errorf("type parameter fields are not supported: %s", typ)
	}
	switch t := typ.Underlying().(type) {
	case *types.Basic:
		value := "0"
		switch {
		case t.Info()&types.IsBoolean != 0:
			value = "false"
		case t.Info()&types.IsString != 0:
			value = `""`
		case t.Kind() == types.UnsafePointer:
			value = "nil"
		case t.Info()&types.IsNumeric == 0:
			return fmt.Errorf("unsupported basic type %s", typ)
		}
		fmt.Fprintf(b, "%s = %s\n", expr, value)
	case *types.Slice:
		fmt.Fprintf(b, "%s = %s[:0]\n", expr, expr)
	case *types.Map:
		fmt.Fprintf(b, "clear(%s)\n", expr)
	case *types.Pointer:
		// A recursively defined pointer type has no finite value to reset.
		if depth > 100 {
			return fmt.Errorf("pointer nesting is recursive or too deep")
		}
		fmt.Fprintf(b, "if %s != nil {\n", expr)
		if err := resetField(b, "(*"+expr+")", t.Elem(), depth+1); err != nil {
			return err
		}
		b.WriteString("}\n")
	case *types.Struct:
		fmt.Fprintf(b, "if resetter, ok := any(&%s).(interface { Reset() }); ok { resetter.Reset() }\n", expr)
	case *types.Array:
		index := fmt.Sprintf("resetIndex%d", depth)
		fmt.Fprintf(b, "for %s := range %s {\n", index, expr)
		if err := resetField(b, expr+"["+index+"]", t.Elem(), depth+1); err != nil {
			return err
		}
		b.WriteString("}\n")
	case *types.Interface, *types.Chan, *types.Signature:
		fmt.Fprintf(b, "%s = nil\n", expr)
	default:
		return fmt.Errorf("unsupported type %s", typ)
	}
	return nil
}
